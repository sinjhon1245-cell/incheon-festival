-- 일정에 '일자' 칸 추가 (schedule_items.event_date)
--
--   2026 행사는 11. 13.(금) ~ 11. 14.(토) 이틀입니다. 그런데 일정 표에는
--   시작·종료 시각('HH:MM')만 있고 날짜가 없어서, 어느 날 일정인지 표에
--   적어 둘 방법이 없었습니다.
--
--   이 파일은 날짜를 적을 칸만 만듭니다. 값은 채우지 않습니다.
--
-- 사용법: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.
--         여러 번 실행해도 안전합니다. 기존 데이터는 하나도 건드리지
--         않습니다(추가만 합니다).
--
-- 선행: migration-portal.sql (schedule_items 의 운영 칼럼)
-- RLS: 바꾸지 않습니다. 기존 열람·편집 정책이 그대로 적용됩니다.
--
-- ⚠️ 기존 일정의 event_date 를 이 파일에서 11/13 이나 11/14 로
--    짐작해 채우지 않습니다. 지금 들어 있는 일정이 어느 날 것인지
--    확정된 자료가 없기 때문입니다. 확정되면 관리자 → 일정에서
--    한 건씩 고르거나, 그때 따로 UPDATE 를 준비합니다.
--
--    비워 두어도 포털은 정상 동작합니다. 날짜가 없는 일정은 행사
--    첫날(11/13) 것으로만 표시되고, 둘째 날 탭에는 나오지 않습니다.
-- ===================================================================


-- ═══════════════════════════════════════════════════════════════
-- 1. 일자 칸
--
-- date 입니다(timestamptz 가 아닙니다). 시각은 start_time · end_time
-- 이 따로 갖고 있고, 날짜에 시간대를 섞으면 '11/13 00:00 KST' 가
-- 서버 시간대에 따라 11/12 로 보이는 사고가 납니다.
--
-- not null 로 두지 않습니다. 이미 들어 있는 13건을 채울 방법이
-- 없어서, not null 을 걸면 이 마이그레이션 자체가 실패합니다.
-- ═══════════════════════════════════════════════════════════════
alter table public.schedule_items
  add column if not exists event_date date;

comment on column public.schedule_items.event_date is
  '일정 날짜(YYYY-MM-DD). 비어 있으면 포털이 행사 첫날 일정으로 봅니다.';


-- ═══════════════════════════════════════════════════════════════
-- 2. 날짜로 훑는 조회를 위한 인덱스
--
-- 일정은 많아야 수백 건이라 없어도 되지만, 포털이 늘 '그날 일정'
-- 으로 거르기 때문에 같은 모양으로 하나 둡니다.
-- ═══════════════════════════════════════════════════════════════
create index if not exists schedule_items_event_date_idx
  on public.schedule_items (event_date, start_time);


-- ═══════════════════════════════════════════════════════════════
-- 3. 확인
--
-- 칸이 생겼는지, 아직 날짜가 없는 일정이 몇 건인지 봅니다.
-- ═══════════════════════════════════════════════════════════════
select
  count(*)                                   as 전체_일정,
  count(event_date)                          as 일자_있음,
  count(*) - count(event_date)               as 일자_없음_첫날로_표시
from public.schedule_items;
