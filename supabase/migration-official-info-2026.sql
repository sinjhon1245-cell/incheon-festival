-- ===================================================================
-- 2026 행사 기본정보 — 2026. 9. 29. 공식 안내 공문 반영 (settings)
--
--   행사명  2026 인천 AI미래채움 교육페스티벌
--   일시    2026. 11. 6.(금) ~ 11. 7.(토), 10:00 ~ 17:00 (KST)
--   장소    인천 상상플랫폼 · 인천광역시 제물포구 월미로 33
--
--   바뀌는 것
--     · 행사명    '2026년 인천 AI·SW미래채움 …' → 공식 명칭
--     · 장소·주소 송도컨벤시아 → 인천 상상플랫폼
--     · 운영시간 표기의 물결표(~)
--     · footer_note  옛 '검토용 예시 데이터입니다' → 변경 가능성 안내
--                    (포털 홈 맨 아래에 한 번 보입니다)
--     · venue_detail 옛 행사장의 홀 번호가 남아 있지 않도록 비웁니다
--                    (확정되면 관리자 → 기본정보에서 채웁니다)
--   개막·종료 일시는 이미 맞는 값이라도 같은 값으로 다시 적습니다.
--
-- 표 구조 · RLS 는 건드리지 않습니다. 값만 바꿉니다.
--
-- 사용법: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.
-- 여러 번 실행해도 결과가 같습니다.
-- ===================================================================

update public.settings set
  event_title   = '2026 인천 AI미래채움 교육페스티벌',
  event_start   = '2026-11-06T10:00:00+09:00',
  event_end     = '2026-11-07T17:00:00+09:00',
  date_label    = '2026. 11. 6.(금) ~ 11. 7.(토)',
  time_label    = '10:00 ~ 17:00',
  venue         = '인천 상상플랫폼',
  venue_detail  = '',
  venue_address = '인천광역시 제물포구 월미로 33',
  footer_note   = '세부 운영 일정, 부스 배치 및 현장 안내는 확정되는 대로 반영됩니다. 운영 내용 및 규모는 변경될 수 있습니다.'
where id = 1;

-- 확인
select event_title, event_start, event_end, date_label, time_label,
       venue, venue_address, footer_note
from public.settings where id = 1;
