-- ===================================================================
-- 2026 행사 기간 기본값 보정 (settings.event_end)
--
--   확정된 행사 기간
--     2026. 11. 6.(금) 10:00  ~  2026. 11. 7.(토) 17:00  (KST)
--
--   문제: migration-portal.sql 은 event_end 가 비어 있으면
--         event_start + 7시간 으로 채웁니다. 하루 행사를 전제로 한
--         값이라, 새 환경에서 schema.sql → migration-portal.sql 을
--         차례로 돌리면 종료가 2026-11-06 17:00 이 됩니다.
--         그러면 포털이 이 행사를 '하루 행사' 로 보고 11/7 날짜
--         탭과 2일차 판단이 사라집니다.
--
--   해결: 지난 마이그레이션을 고쳐 쓰지 않습니다(이미 실행된 파일을
--         바꾸면 어느 환경이 무엇을 돌렸는지 알 수 없게 됩니다).
--         대신 이 파일이 '아직 옛 기본값 그대로인 경우에만' 종료
--         일시를 바로잡습니다.
--
-- 사용법: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.
--         새로 만든 환경에서는 schema.sql · migration-portal.sql
--         다음에 한 번 돌립니다.
--
-- 여러 번 실행해도 안전합니다. 아래 update 는 조건이 맞을 때만
-- 움직이고, 한 번 고쳐진 뒤에는 조건에 걸리지 않습니다.
--
-- ⚠️ 사람이 직접 넣은 값은 건드리지 않습니다.
--    event_start 가 2026-11-06 10:00 (KST) 이고, event_end 가
--    비어 있거나 '시작 +7시간' 인 경우에만 고칩니다. 운영 중에
--    다른 기간으로 바꿔 둔 환경은 그대로 둡니다.
--
--    행사일이 바뀌면(10/17 → 11/13~14 → 11/6~7) 이 파일의 날짜도
--    함께 고칩니다. 아직 어느 환경에도 적용된 적이 없는 파일이라
--    (마이그레이션 원장에 없음) 고쳐도 기록이 어긋나지 않습니다.
--
-- 이 파일은 settings 한 줄(id = 1)만 다룹니다. 일정·부스·공지 등
-- 다른 표는 읽지도 쓰지도 않습니다. DELETE · DROP 없습니다.
-- ===================================================================


-- ═══════════════════════════════════════════════════════════════
-- 1. 종료 일시 보정
-- ═══════════════════════════════════════════════════════════════
update public.settings
set event_end = timestamptz '2026-11-07 17:00:00+09'
where id = 1
  and event_start = timestamptz '2026-11-06 10:00:00+09'
  and (
    event_end is null
    or event_end = event_start + interval '7 hours'   -- migration-portal.sql 의 하루 행사 기본값
    or event_end < event_start                        -- 잘못 들어간 값
  );


-- ═══════════════════════════════════════════════════════════════
-- 2. 날짜 표기 보정
--
-- 화면에 그대로 찍히는 글자입니다. 기간과 어긋나 있으면 사람이
-- 읽는 정보와 계산에 쓰는 값이 서로 다른 말을 하게 됩니다.
--
-- 비어 있거나, 알려진 옛 값(2026. 10. 17. · 11. 13.~14.)일 때만 채웁니다.
-- '고쳐야 할 것 같은 문구' 를 넓게 잡으면 관리자가 직접 적어 둔
-- 표기를 덮어씁니다. 확실한 두 경우만 봅니다.
-- ═══════════════════════════════════════════════════════════════
update public.settings
set date_label = '2026. 11. 6.(금) ~ 11. 7.(토)'
where id = 1
  and event_start = timestamptz '2026-11-06 10:00:00+09'
  and (coalesce(trim(date_label), '') = '' or trim(date_label) like '2026. 10. 17.%' or trim(date_label) like '2026. 11. 13.%');


-- ═══════════════════════════════════════════════════════════════
-- 3. 확인
--
-- 기간이 이틀로 잡혔는지 봅니다. 행사일수가 2 여야 합니다.
-- ═══════════════════════════════════════════════════════════════
select
  event_start,
  event_end,
  date_label,
  venue,
  (date(event_end at time zone 'Asia/Seoul')
   - date(event_start at time zone 'Asia/Seoul')) + 1 as 행사일수
from public.settings
where id = 1;
